export const doctorById = (id: string): Doctor => DOCTORS.find((d) => d.id === id) ?? DOCTORS[0]

/** Врач по умолчанию для системы: тот, кто ведёт её в первую очередь; иначе терапевт. */
export const doctorFor = (systemId: SystemId): Doctor => DOCTORS.find((d) => d.systems.includes(systemId)) ?? DOCTORS[0]

/** «к кардиологу», «к ортопеду-травматологу» */
export const roleTo = (d: Doctor) =>
  d.role
    .toLowerCase()
    .split('-')
    .map((w) => (w.endsWith('ог') ? `${w}у` : w.endsWith('ед') ? `${w}у` : w.endsWith('ь') ? `${w.slice(0, -1)}ю` : w))
    .join('-')

export const doctorPhoto = (id: string) => `${import.meta.env.BASE_URL}doctors/${id}.webp`
export const threadOf = (doctorId: string) => `t-${doctorId}`
